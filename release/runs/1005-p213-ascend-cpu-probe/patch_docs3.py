FILES = ["ascend/kernels/gemm_asc.py", "ascend/kernels/gemm_bwd_dw_asc.py",
         "ascend/kernels/rope_asc.py", "ascend/kernels/add_ln_asc.py",
         "ascend/kernels/letter_readout_asc.py", "ascend/kernels/attn_sw_asc.py",
         "ascend/kernels/gdn_asc.py", "ascend/kernels/ascend_env.py", "ascend/selfcheck.py"]

total = 0
for rel in FILES:
    path = Path(rel)
    src = path.read_text()
    tree = ast.parse(src)
    lines = src.splitlines(keepends=True)
    todo: dict[str, list] = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.FunctionDef) or node.name.startswith("_"):
            continue
        seg = ast.get_source_segment(src, node) or ""
        if len([ln for ln in seg.splitlines() if ln.strip()]) <= 4:
            continue
        if (ast.get_docstring(node) or "").strip():
            continue
        todo.setdefault(node.name, []).append(node)
    plans = []
    for name, nodes in todo.items():
        nodes.sort(key=lambda x: x.lineno)
        texts = TEXTS[name]
        assert len(texts) >= len(nodes), (rel, name, len(texts), len(nodes))
        for node, text in zip(nodes, texts):
            idx = node.body[0].lineno - 1
            pad = " " * node.body[0].col_offset
            body = text.strip("\n")
            block = f'{pad}"""{body}\n{pad}"""\n'
            plans.append((idx, block))
    for idx, block in sorted(plans, reverse=True):        # 自下而上插，避免行号偏移
        lines.insert(idx, block)
    path.write_text("".join(lines))
    ast.parse(path.read_text())
    total += len(plans)
    print(f"{rel}: +{len(plans)} docstring, SYNTAX OK")
print("TOTAL", total)
