"""production.backbone — HF 检查点到自研算子栈的张量布局层。

【做什么】
    把 HuggingFace safetensors 里的权重，换成二阶段自研算子栈（`sys1/kernels/` 三件套那套
    契约）认得的形状与顺序：三条投影拼成一摞打包的 qkv、查询里的门控列单独摘出来、
    分组注意力的小头补成大头、旋转位置编码的配对方式重排成内核的"前后两半互相搭一手"。

【怎么做】
    两个文件分工。`layout.py` 只做"纯形状与顺序"的换算（吃张量回张量，不碰磁盘也不碰模型），
    每个函数都自带一个可独立断言的下标列子（permutation）——所以逐元素对拍不需要真权重。
    `loader.py` 负责搬运：按 index 从 safetensors 分片里读出需要的张量、调用 layout 换算、
    再用自研栈口径跑一层前向，与 HF 那一层的输出对拍（容差内）。
    布局换算的四条实招（Qwen3.5-0.8B 权重实证）：
      ① gemm 契约：自研栈 `gemm.forward(A, W)` 算 `A @ Wᵀ`，W 是 (N,K) 行主序——**与 HF
         nn.Linear 完全一致，故不需要转置**；需要动的只有"行的分组顺序"。
      ② 打包 qkv：自研栈把 q/k/v 拼成一摞，视图是 `(3, heads, head_dim)`；HF 是三条独立投影，
         且 k/v 只有 `kv_heads` 个（分组注意力）→ 按头 repeat_interleave 补齐。
      ③ 门控查询：`attn_output_gate=true` 时 q_proj 每个头交出的宽度是 `head_dim*2`（前半是
         查询、后半是出口门）→ 先拆列再打包。
      ④ 旋转配对：HF 只对每个头的前 `rotary_dim`（=head_dim×0.25）维做 rotate-half，配对是
         (i, i+rotary_dim/2)；自研栈的 rope 内核写死"整头前后两半配对" (j, head_dim/2)。
         于是给每个头挑一个坐标置换，把 HF 的配对搬进内核的配对，未旋转的坐标排到后面并
         配上 cos=1/sin=0 的恒等角表；同头的逐坐标缩放（q_norm/k_norm）跟着同一个置换重排，
         RMSNorm 对置换可交换，所以数值不变。

【为什么】
    布局错了，p2-13 的方言件就把同一份权重算成另一回事，而这类错不会崩、只会静默给出接近
    但不等于的数——最难归因。所以先把"布局"从"算子"里切出来单独可断言：置换列子、
    行切片、角表扩展三样都能逐元素验；再用一层真前向与 HF 对拍兜住整体。
    被否方案一：让自研 rope 内核改成支持任意配对——内核要保持最简形态（`rope_kernel.py`
    的【为什么】已定：槽位/配对的花哨口径一律落回退路径），改内核不如改数据布局。
    被否方案二：整层直接照抄 HF 的写法当"自研栈"——那是把接缝藏起来，p2-13 上昇腾时
    才发现布局对不上，代价是整条移植重排。
    被否方案三：把 MLP 的门控折算成自研栈的"升宽—关卡—压回"两矩阵——SiLU 门控与 gelu
    前馈不是同一族函数，折不出等价；正确出路是 p2-13 补一个带门的 MLP 件，本件只把三块
    权重按原样搬好并在产物里标注"待门控件"。
"""
